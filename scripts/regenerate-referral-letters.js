/**
 * Regenerates stored referral letters, archiving the superseded copy first.
 *
 *   node scripts/regenerate-referral-letters.js --dry-run          # report only
 *   node scripts/regenerate-referral-letters.js --stale            # only pre-fix letters
 *   node scripts/regenerate-referral-letters.js --queue-id 510002  # one referral
 *   node scripts/regenerate-referral-letters.js --all              # every letter
 *
 * WHY: letters issued before the official letterhead and the address fix carry
 * the text-only fallback header and read "a resident of ______", because
 * findReferralById never selected users.location or pesoadmin_job_posts.location.
 * Regenerating produces the letter that should have been issued.
 *
 * NOTHING IS DESTROYED. The current copy is written to referral_letter_archive
 * before being replaced (migration 022). The archive is what was actually
 * delivered to the citizen; the new row is what the record should say.
 *
 * THE DATE DOES NOT MOVE. pdfService dates a letter from reviewed_at, not from
 * the clock, so a regenerated letter keeps its original approval date.
 *
 * NOTHING IS RE-SENT. No email, no notification, no outbox job. Re-issuing a
 * corrected letter to a person is a PESO decision, made per person, and is
 * deliberately not automated.
 */

const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });

const db = require('../db');
const referralRepository = require('../repositories/referralRepository');
const { generateReferralLetter } = require('../services/pdfService');

const argv = process.argv.slice(2);
const DRY_RUN = argv.includes('--dry-run');
const ALL = argv.includes('--all');
const STALE = argv.includes('--stale');

const queueIdArg = (() => {
	const i = argv.indexOf('--queue-id');
	if (i === -1) return null;
	const parsed = Number.parseInt(argv[i + 1], 10);
	return Number.isInteger(parsed) ? parsed : null;
})();

// A letter produced before the letterhead existed is ~2-3KB; with the artwork
// embedded it is ~397KB. Size is therefore a reliable, cheap marker for "was
// generated by the old code path" without re-rendering anything to compare.
const STALE_BYTE_CEILING = 100000;

function usage() {
	console.log('Choose exactly one selector:\n');
	console.log('  --stale             letters below 100KB (missing letterhead / address)');
	console.log('  --queue-id <id>     a single referral');
	console.log('  --all               every stored letter');
	console.log('\nAdd --dry-run to preview without writing.\n');
}

async function selectTargets() {
	if (queueIdArg !== null) {
		const [rows] = await db.query(
			'SELECT queue_id, reference_number, byte_size, source, created_at FROM referral_letter_files WHERE queue_id = ?',
			[queueIdArg]
		);
		return rows;
	}

	if (STALE) {
		const [rows] = await db.query(
			`SELECT queue_id, reference_number, byte_size, source, created_at
			   FROM referral_letter_files
			  WHERE byte_size < ?
			  ORDER BY queue_id`,
			[STALE_BYTE_CEILING]
		);
		return rows;
	}

	const [rows] = await db.query(
		'SELECT queue_id, reference_number, byte_size, source, created_at FROM referral_letter_files ORDER BY queue_id'
	);
	return rows;
}

async function regenerateOne(target) {
	const referral = await referralRepository.findReferralById(target.queue_id);

	if (!referral) {
		throw new Error('referral row disappeared');
	}
	if (!referral.reference_number) {
		throw new Error('no reference number');
	}

	const { buffer } = await generateReferralLetter(referral);

	// Refuse to replace a good letter with a worse one. If the regenerated file
	// is not materially larger than a bare text letter, the letterhead did not
	// load -- overwriting would quietly destroy nothing but also fix nothing,
	// and would burn the archive slot for no gain.
	if (buffer.length < STALE_BYTE_CEILING && target.byte_size < STALE_BYTE_CEILING) {
		throw new Error(
			`regenerated letter is only ${buffer.length} bytes -- letterhead did not load. ` +
			'Check assets/letterhead/letterhead.png exists and is readable.'
		);
	}

	const connection = await db.getConnection();

	try {
		await connection.beginTransaction();

		// ARCHIVE FIRST. If anything after this fails the transaction rolls back
		// and the delivered copy is still the live one -- never a state where the
		// original is gone and the replacement did not land.
		await connection.query(
			`INSERT INTO referral_letter_archive
				(queue_id, reference_number, content_base64, byte_size, original_source, original_created_at, archived_reason)
			 SELECT queue_id, reference_number, content_base64, byte_size, source, created_at, ?
			   FROM referral_letter_files
			  WHERE queue_id = ?`,
			['Superseded by regeneration: official letterhead + address fields', target.queue_id]
		);

		await connection.query(
			`UPDATE referral_letter_files
				SET content_base64 = ?, byte_size = ?, source = 'regenerated'
			  WHERE queue_id = ?`,
			[buffer.toString('base64'), buffer.length, target.queue_id]
		);

		await referralRepository.logActivity({
			queueId: target.queue_id,
			actorId: null,
			action: 'LETTER_REGENERATED',
			detail: `Letter ${target.reference_number} regenerated (${target.byte_size} -> ${buffer.length} bytes). Previous version archived. Not re-sent.`
		}, connection);

		await connection.commit();
	} catch (error) {
		await connection.rollback();
		throw error;
	} finally {
		connection.release();
	}

	return buffer.length;
}

async function main() {
	if (!ALL && !STALE && queueIdArg === null) {
		usage();
		return;
	}

	const targets = await selectTargets();

	if (targets.length === 0) {
		console.log('[Regenerate] Nothing matched that selector.');
		return;
	}

	console.log(DRY_RUN
		? `[Regenerate] DRY RUN -- no writes. ${targets.length} letter(s) matched.\n`
		: `[Regenerate] ${targets.length} letter(s) matched. Archiving then regenerating.\n`);

	let done = 0;
	let failed = 0;

	for (const target of targets) {
		const label = target.reference_number || `queue ${target.queue_id}`;

		if (DRY_RUN) {
			console.log(`  WOULD REGENERATE  ${label}  (currently ${(target.byte_size / 1024).toFixed(1)} KB, source=${target.source})`);
			done++;
			continue;
		}

		try {
			const newSize = await regenerateOne(target);
			console.log(`  REGENERATED  ${label}  ${(target.byte_size / 1024).toFixed(1)} KB -> ${(newSize / 1024).toFixed(1)} KB`);
			done++;
		} catch (error) {
			console.error(`  FAILED       ${label}  -- ${error.message}`);
			failed++;
		}
	}

	console.log('\n────────────────────────────────────────');
	console.log(`  ${DRY_RUN ? 'Would regenerate' : 'Regenerated'}: ${done}`);
	if (failed > 0) console.log(`  Failed: ${failed}  (originals untouched)`);
	console.log('────────────────────────────────────────');

	if (!DRY_RUN && done > 0) {
		console.log('\nSuperseded copies are in referral_letter_archive -- nothing was deleted.');
		console.log('No emails were sent. Recipients still hold their original letter.');
	}
}

main()
	.then(() => process.exit(0))
	.catch((error) => {
		console.error('[Regenerate] FAILED:', error.message);
		process.exit(1);
	});
