-- =============================================================================
-- PESO Kabankalan — Postgres schema (Supabase re-platform experiment)
-- Branch: experiment/postgres-supabase
--
-- SOURCE OF TRUTH: this is a faithful translation of the LIVE TiDB schema
-- (all 54 migrations + boot-time ALTERs, captured read-only via SHOW CREATE
-- TABLE on 2026-09-15), NOT a re-port of the 54 incremental MySQL migrations —
-- because migration 000 was baselined on a pre-existing schema, so the core
-- tables (users, job_applications, pesoadmin_job_posts, conversations, …) never
-- existed as migration DDL.
--
-- TRANSLATION RULES APPLIED
--   int AUTO_INCREMENT PK  -> integer GENERATED BY DEFAULT AS IDENTITY
--                            (BY DEFAULT, not ALWAYS, so explicit-id inserts work)
--   bigint AUTO_INCREMENT  -> bigint  GENERATED BY DEFAULT AS IDENTITY
--   longtext               -> text            (Postgres text is unbounded)
--   datetime / timestamp   -> timestamptz     (matches the app's mysql2
--                            timezone:'Z' contract: absolute UTC instants)
--   tinyint(1)             -> smallint        (KEEP 0/1 semantics — the JS/JSX
--                            reads these as 0/1; real boolean would break `=== 1`)
--   decimal(p,s)           -> numeric(p,s)
--   enum(...)              -> varchar(n)       (no rigid CHECK: the app appends
--                            status values over time and validates in code)
--   ON UPDATE CURRENT_TIMESTAMP -> a BEFORE UPDATE trigger (Postgres has no
--                            column-level ON UPDATE) that only fires when the
--                            statement did NOT set the column itself (faithful
--                            to MySQL, which lets an explicit value win)
--
-- STRUCTURE: (1) trigger fns, (2) tables (PK + UNIQUE inline, NO FK so order
-- doesn't matter), (3) FKs via ALTER, (4) secondary indexes, (5) updated-at
-- triggers, (6) minimal seed. Apply with: node scripts/pg-bootstrap.js
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. "ON UPDATE CURRENT_TIMESTAMP" emulation
-- Each fn bumps its column only if the UPDATE left it unchanged, so an explicit
-- `SET updated_at = ...` still wins — exactly MySQL's behaviour.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION trg_touch_updated_at() RETURNS trigger AS $$
BEGIN
	IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN NEW.updated_at := CURRENT_TIMESTAMP; END IF;
	RETURN NEW;
END; $$ LANGUAGE plpgsql;

